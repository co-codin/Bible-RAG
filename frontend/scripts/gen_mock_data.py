"""Generate src/api/mockData.ts with REAL verse texts pulled from the jsonl data.

Quran Chinese (Ma Jian) is copyrighted (until end of 2028 in China), so it is NEVER
written into this committed file: Quran records get `zh: null`. Only the surah name
(from surahs.json) is kept for labels.
Usage: python3 scripts/gen_mock_data.py /path/to/bible-data-root
"""
import json, sys, pathlib
root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/workspace/bible")
REFS = {
  "bible": [("Matt",6,14),("Matt",6,15),("Eph",4,32),("Col",3,13),("1John",1,9),
            ("1Cor",13,4),("1Cor",13,13),("John",3,16),("1John",4,8),("Ps",23,1)],
  "quran": [("Q002",2,153),("Q002",2,155),("Q003",3,200),("Q039",39,10),("Q103",103,3),
            ("Q042",42,43),("Q024",24,22)],
}
def load(p):
    d = {}
    for line in open(p, encoding="utf-8"):
        r = json.loads(line); d[(r["book_code"], r["chapter"], r["verse"])] = r
    return d
B = root / "bible-rag-data"; Q = root / "quran-data"
books = {v["osis"]: v for v in json.load(open(B / "books.json")).values()}
surahs = {s["code"]: s for s in json.load(open(Q / "surahs.json"))}
kjv, cuv = load(B / "kjv.jsonl"), load(B / "cuv.jsonl")
qen = load(Q / "quran_en.jsonl")  # quran_zh.jsonl (Ma Jian) intentionally NOT read
out = {}
for corpus, refs in REFS.items():
    for code, c, v in refs:
        e = (kjv if corpus == "bible" else qen)[(code, c, v)]
        z = cuv[(code, c, v)] if corpus == "bible" else None
        if corpus == "bible":
            ben, bzh = books[code]["en"], books[code]["zh"]
        else:
            ben, bzh = f"Quran {surahs[code]['translit']}", f"古兰经·{surahs[code]['zh']}"
        ref = f"{code}.{c}.{v}"
        out[ref] = {"canonRef": ref, "corpus": corpus, "bookCode": code, "chapter": c, "verse": v,
            "bookName": {"en": ben, "zh": bzh},
            "en": {"translation": e["translation"], "text": e["text"]},
            "zh": {"translation": z["translation"], "text": z["text"]} if z else None}
ts = ("// AUTO-GENERATED by scripts/gen_mock_data.py from the project's jsonl data.\n"
      "// Verse texts are real (KJV, CUV, Pickthall). Quran zh is null: Ma Jian is copyrighted\n"
      "// and only available after a local build. Do not edit by hand.\n"
      "import type { VerseRecord } from './types'\n\n"
      f"export const MOCK_VERSES: Record<string, VerseRecord> = {json.dumps(out, ensure_ascii=False, indent=2)}\n")
p = pathlib.Path(__file__).resolve().parent.parent / "src/api/mockData.ts"
p.parent.mkdir(parents=True, exist_ok=True); p.write_text(ts, encoding="utf-8")
for k, r in out.items(): print(k, "|", r["en"]["text"][:70], "|", (r["zh"] or {}).get("text", "<null>")[:30])
